# 8. Profit concentration
# What percentage of total profit is generated by the top-performing sub-categories and customers?

with sub_category_profit as(
     select Sub_Category as segment,
     sum(Profit) as total_profit
     from details group by Sub_Category
),
customer_profit as(
    select o.CustomerName as segment,
    sum(d.Profit) as total_profit
    from Orders o join Details d on o.Order_ID=d.Order_ID
    group by o.CustomerName
)
select 'Sub_Category' as segment_type,
           ROUND(
        SUM(total_profit) /
        (SELECT SUM(total_profit) FROM sub_category_profit) * 100,
        2
    ) AS profit_percentage
FROM (
    SELECT
        segment,
        total_profit,
        ROW_NUMBER() OVER (ORDER BY total_profit DESC) AS profit_rank
    FROM sub_category_profit
) s
WHERE profit_rank <= 5

UNION ALL

SELECT
    'Customer' AS segment_type,
    ROUND(
        SUM(total_profit) /
        (SELECT SUM(total_profit) FROM customer_profit) * 100,
        2
    ) AS profit_percentage
FROM (
    SELECT
        segment,
        total_profit,
        ROW_NUMBER() OVER (ORDER BY total_profit DESC) AS profit_rank
    FROM customer_profit
) c
WHERE profit_rank <= 5;
