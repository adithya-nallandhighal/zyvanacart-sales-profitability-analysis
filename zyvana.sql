# 11. Low-profit high-volume segments
# Which segments have high quantities sold but comparatively low profit, indicating potential opportunities to improve the profitability of high-volume sales?

WITH subcategory_analysis AS (
    SELECT
        sub_category,
        SUM(Quantity) AS total_quantity,
        SUM(Amount) AS total_sales,
        SUM(Profit) AS total_profit,
        SUM(Profit) / SUM(Amount) * 100 AS profit_margin
    FROM Details
    GROUP BY sub_category
)
SELECT
    sub_category,
    total_quantity,
    total_sales,
    total_profit,
    ROUND(profit_margin, 2) AS profit_margin
FROM subcategory_analysis
WHERE total_quantity >= (
    SELECT AVG(total_quantity)
    FROM subcategory_analysis
)
AND total_profit < (
    SELECT AVG(total_profit)
    FROM subcategory_analysis
)
ORDER BY total_quantity DESC;
