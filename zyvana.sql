# 10. Payment behavior vs profitability
# Do different payment methods show meaningful differences in average order value or profit contribution?

with order_payment as(
     select o.Order_Id,
            d.PaymentMode,
            sum(d.Amount) as order_value,
            sum(d.Profit) as order_profit
            from Orders o join Details d on o.Order_ID=d.Order_ID
            group by o.Order_ID, d.PaymentMode
),
payment_analysis as(
       select PaymentMode,
              count(Order_ID) as total_orders,
              avg(Order_Value) as avg_order_value,
              sum(order_profit) as total_order_profit
              from order_payment
              group by PaymentMode
)
select PaymentMode,
       total_orders,
       round(avg_order_value,2) as avg_order_value,
       total_order_profit,
       round(
           total_order_profit/(select sum(total_order_profit) from payment_analysis)*100,2
		) as profit_contribution
from payment_analysis
order by total_order_profit desc;
