# 12. Profitability ranking
# Rank customers and sub-categories based on profit contribution to identify the strongest and weakest contributors.

WITH customer_profit AS (
    SELECT
        o.CustomerName AS segment,
        SUM(d.Profit) AS total_profit
    FROM Orders o
    JOIN Details d
        ON o.Order_ID = d.Order_ID
    GROUP BY o.CustomerName
),

subcategory_profit AS (
    SELECT
        sub_category AS segment,
        SUM(Profit) AS total_profit
    FROM Details
    GROUP BY sub_category
)

SELECT
    'Customer' AS segment_type,
    segment,
    total_profit,
    DENSE_RANK() OVER (ORDER BY total_profit DESC) AS profit_rank
FROM customer_profit

UNION ALL

SELECT
    'Sub-Category' AS segment_type,
    segment,
    total_profit,
    DENSE_RANK() OVER (ORDER BY total_profit DESC) AS profit_rank
FROM subcategory_profit
ORDER BY segment_type, profit_rank;


