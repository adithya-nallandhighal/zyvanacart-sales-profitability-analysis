# 5. Customer order economics
# Which customers place multiple orders but generate relatively low profit per order?

with customer_orders as(
	  select o.CustomerName,
			 o.Order_ID,
             sum(d.Profit) as total_profit
             from orders o join details d on o.Order_ID=d.Order_ID
             group by o.CustomerName, o.Order_ID
),

customer_economics as(
       select CustomerName,
			  count(Order_ID) as total_orders,
              sum(total_profit) as order_total_profit,
              sum(total_profit)/count(Order_ID) as profit_per_order
			from customer_orders
            group by CustomerName
)

select CustomerName,
       total_orders,
       order_total_profit,
       round(profit_per_order,2) as profit_per_order
	from customer_economics
    where total_orders > 1
       and profit_per_order < (select avg(profit_per_order) from customer_economics)
       order by profit_per_order desc;
