# 4. High-value customer contribution
# What percentage of total sales and profit is generated by the top 10% of customers?

with percentage as (
     select 
        o.CustomerName,
        sum(d.Amount) as total_sales,
        sum(d.Profit) as total_profit
        from orders o 
        join details d on o.Order_ID=d.Order_ID
        group by o.CustomerName
),
ranked_customers as (
      select CustomerName, total_sales, total_profit,
      row_number() over(order by total_sales desc) as customer_rank,
      count(*) over() as total_customers
      from percentage
)
select round(sum(total_sales)/(select sum(total_sales) from percentage)*100,2) as sales_percentage,
round(sum(total_profit)/(select sum(total_profit) from percentage)*100,2) as profit_percentage
from ranked_customers
where customer_rank <=ceil(total_customers*0.10);
